def weighted_text(words, top=60, power=0.75):
    """Space-separated text in which word i appears about top / (i + 1) ** power times."""
    out = []
    for i, w in enumerate(words):
        out += [w] * max(1, round(top / (i + 1) ** power))
    return " ".join(out)
