"""Generate Rust constant tables (named colours, matplotlib colormap LUTs) from the legacy deps."""
import sys
from PIL import ImageColor
import matplotlib
out = sys.argv[1]
names = sorted(ImageColor.colormap.items())
with open(f"{out}/color/names.rs", "w") as f:
    f.write("//! Generated by tools/gen_tables.py from Pillow `ImageColor.colormap`. Do not edit.\n\n")
    f.write("/// Pillow's named colours as `(lowercase name, hex/rgb spec)`, sorted by name.\n")
    f.write("#[rustfmt::skip]\n")
    f.write("pub const NAMED_COLORS: &[(&str, &str)] = &[\n")
    for k, v in names:
        f.write(f'    ("{k}", "{v}"),\n')
    f.write("];\n")
maps = ["viridis", "plasma", "inferno", "magma", "cividis", "hsv", "rainbow", "jet", "cool", "spring", "summer", "autumn", "winter", "gray", "hot", "Blues", "Reds", "Greens"]
with open(f"{out}/color/colormaps.rs", "w") as f:
    f.write("//! Generated by tools/gen_tables.py from matplotlib %s 256-entry LUTs. Do not edit.\n\n" % matplotlib.__version__)
    f.write("/// `(name, [[r, g, b]; 256])` with the exact `f64` values of matplotlib's `_lut`.\n")
    f.write("#[rustfmt::skip]\n")
    f.write("pub const COLORMAPS: &[(&str, [[f64; 3]; 256])] = &[\n")
    for m in maps:
        cm = matplotlib.colormaps[m]; cm._init()
        rows = ", ".join("[%r, %r, %r]" % tuple(float(c) for c in cm._lut[i][:3]) for i in range(256))
        f.write(f'    ("{m}", [{rows}]),\n')
    f.write("];\n")
